export const tabCode = '\t'.charCodeAt(0);
export const newlineCode = '\n'.charCodeAt(0);
export const returnCode = '\r'.charCodeAt(0);
export const spaceCode = ' '.charCodeAt(0);
export const ampersandCode = '&'.charCodeAt(0);
export const openParenCode = '('.charCodeAt(0);
export const closeParenCode = ')'.charCodeAt(0);
export const colonCode = ':'.charCodeAt(0);
export const ltCode = '<'.charCodeAt(0);
export const gtCode = '>'.charCodeAt(0);
export const openBracketCode = '['.charCodeAt(0);
export const backslashCode = '\\'.charCodeAt(0);

export const isSpaceOrTab = (c) => c === spaceCode || c === tabCode;
